import AppKit
import UniformTypeIdentifiers

struct ClipboardItem: Codable, Identifiable {
    let id: String
    let kind: ClipboardKind
    /// Preview / plain text / hex / path list.
    let text: String
    let imageFileName: String?
    /// Sidecar for rtf/html/pdf binary under mediaDir.
    let payloadFileName: String?
    let createdAt: Date
    var ocrText: String?
    var contentHash: String?
    /// Pinned clips stay at the top and survive Clear / trim.
    var pinned: Bool

    enum CodingKeys: String, CodingKey {
        case id, kind, text, imageFileName, payloadFileName, createdAt, ocrText, contentHash, pinned
    }

    init(
        id: String,
        kind: ClipboardKind,
        text: String,
        imageFileName: String? = nil,
        payloadFileName: String? = nil,
        createdAt: Date = Date(),
        ocrText: String? = nil,
        contentHash: String? = nil,
        pinned: Bool = false
    ) {
        self.id = id
        self.kind = kind
        self.text = text
        self.imageFileName = imageFileName
        self.payloadFileName = payloadFileName
        self.createdAt = createdAt
        self.ocrText = ocrText
        self.contentHash = contentHash
        self.pinned = pinned
    }

    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = try c.decode(String.self, forKey: .id)
        kind = try c.decode(ClipboardKind.self, forKey: .kind)
        text = try c.decode(String.self, forKey: .text)
        imageFileName = try c.decodeIfPresent(String.self, forKey: .imageFileName)
        payloadFileName = try c.decodeIfPresent(String.self, forKey: .payloadFileName)
        createdAt = try c.decode(Date.self, forKey: .createdAt)
        ocrText = try c.decodeIfPresent(String.self, forKey: .ocrText)
        contentHash = try c.decodeIfPresent(String.self, forKey: .contentHash)
        pinned = try c.decodeIfPresent(Bool.self, forKey: .pinned) ?? false
    }
}

final class ClipboardStore {
    static let shared = ClipboardStore()

    private(set) var items: [ClipboardItem] = []
    private var timer: Timer?
    private var cleanupTimer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var maxItems = 200
    private var suppressCaptureUntil: Date?
    var onHistoryChanged: (() -> Void)?

    private let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private let autoGenType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    private let universalType = NSPasteboard.PasteboardType("com.apple.is-remote-clipboard")

    func applyMaxItems(_ limit: Int) {
        maxItems = max(20, min(limit, 1000))
        trimOverflow()
    }

    func suppressNextCapture(for seconds: TimeInterval = 0.8) {
        suppressCaptureUntil = Date().addingTimeInterval(seconds)
        lastChangeCount = NSPasteboard.general.changeCount
    }

    func notePasteboardWritten() {
        lastChangeCount = NSPasteboard.general.changeCount
    }

    private var rootDir: URL { BlitzDatabase.supportDirectory }

    var mediaDir: URL {
        let dir = rootDir.appendingPathComponent("clipboard-media", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir
    }

    private var storeURL: URL { rootDir.appendingPathComponent("clipboard.json") }

    func imageURL(for item: ClipboardItem) -> URL? {
        guard let name = item.imageFileName else { return nil }
        return mediaDir.appendingPathComponent(name)
    }

    func payloadURL(for item: ClipboardItem) -> URL? {
        guard let name = item.payloadFileName else { return nil }
        return mediaDir.appendingPathComponent(name)
    }

    func start() {
        let store = SettingsStore.shared
        maxItems = store.clipboardMaxItems
        load()
        lastChangeCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.35, repeats: true) { [weak self] _ in
            self?.poll()
        }
        reschedulePeriodicCleanup()
        ScreenshotObserver.shared.start()
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        cleanupTimer?.invalidate()
        cleanupTimer = nil
        ScreenshotObserver.shared.stop()
        if SettingsStore.shared.clearHistoryOnQuit {
            clear(confirm: false)
        } else {
            save()
        }
    }

    func reschedulePeriodicCleanup() {
        cleanupTimer?.invalidate()
        cleanupTimer = nil
        let store = SettingsStore.shared
        guard store.clearHistoryPeriodically else { return }
        let interval = TimeInterval(store.historyClearInterval.rawValue)
        cleanupTimer = Timer.scheduledTimer(withTimeInterval: interval, repeats: true) { [weak self] _ in
            self?.clear(confirm: false)
        }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount

        if let until = suppressCaptureUntil, Date() < until { return }
        suppressCaptureUntil = nil

        let types = Set(pb.types ?? [])
        if types.contains(transientType) || types.contains(autoGenType) { return }

        let settings = SettingsStore.shared
        if settings.ignoreConcealed, types.contains(concealedType) { return }
        if settings.ignoreUniversalClipboard, types.contains(universalType) { return }

        if isExcludedFrontApp(pasteboardTypes: types) { return }

        let enabled = settings.pasteboardTypes

        // Color (short hex / rgb) wins as dedicated kind when plain string matches.
        if enabled.string,
           let text = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines),
           !text.isEmpty,
           let color = ColorParse.parse(text) {
            captureColor(hex: color.hex, plain: text)
            return
        }

        if enabled.tiff, let image = readImage(from: pb) {
            captureImage(image)
            return
        }

        if enabled.pdf, let pdf = pb.data(forType: .pdf) {
            captureBinary(kind: .pdf, data: pdf, ext: "pdf", preview: "PDF \(pdf.count) bytes")
            return
        }

        if enabled.filenames, let urls = pb.readObjects(forClasses: [NSURL.self], options: [
            .urlReadingFileURLsOnly: true
        ]) as? [URL], !urls.isEmpty, urls.allSatisfy(\.isFileURL) {
            let paths = urls.map(\.path).joined(separator: "\n")
            captureFilePaths(paths)
            return
        }

        if enabled.url, let urlString = pb.string(forType: .URL) ?? pb.string(forType: .string),
           let url = URL(string: urlString), url.scheme != nil,
           (url.scheme == "http" || url.scheme == "https" || url.scheme == "file") {
            // Only treat as URL item when pasteboard advertises URL type or looks like a lone URL.
            if types.contains(.URL) || (urlString == textOneLine(urlString) && urlString.contains("://")) {
                captureURL(url.absoluteString)
                return
            }
        }

        if enabled.rtf, let rtf = pb.data(forType: .rtf) ?? pb.data(forType: .rtfd) {
            let plain = pb.string(forType: .string) ?? ""
            let preview = plain.isEmpty ? "Rich text" : textOneLine(plain)
            let ext = (pb.data(forType: .rtfd) != nil) ? "rtfd" : "rtf"
            // rtfd can be a package; store flat data when available
            if let data = pb.data(forType: .rtf) {
                captureBinary(kind: .rtf, data: data, ext: "rtf", preview: preview, plain: plain)
                return
            }
            captureBinary(kind: .rtf, data: rtf, ext: ext, preview: preview, plain: plain)
            return
        }

        if enabled.html, let html = pb.data(forType: .html) {
            let plain = pb.string(forType: .string) ?? String(data: html, encoding: .utf8) ?? "HTML"
            captureBinary(kind: .html, data: html, ext: "html", preview: textOneLine(plain), plain: plain)
            return
        }

        if enabled.string,
           let text = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines),
           !text.isEmpty,
           shouldRecordText(text) {
            captureText(text)
        }
    }

    private func isExcludedFrontApp(pasteboardTypes: Set<NSPasteboard.PasteboardType>) -> Bool {
        let excluded = SettingsStore.shared.excludedBundleIDs
        guard !excluded.isEmpty else { return false }
        if let bid = NSWorkspace.shared.frontmostApplication?.bundleIdentifier,
           excluded.contains(bid) {
            return true
        }
        // Some extensions stamp a type that prefixes the app id.
        for bid in excluded {
            if pasteboardTypes.contains(where: { bid.hasPrefix($0.rawValue) || $0.rawValue.hasPrefix(bid) }) {
                return true
            }
        }
        return false
    }

    private func shouldRecordText(_ text: String) -> Bool {
        if text.count > 50_000 { return false }
        let compact = text.replacingOccurrences(of: " ", with: "")
        let shortcutOnly = CharacterSet(charactersIn: "⌘⌥⌃⇧⌃⌘+abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789")
        if compact.count <= 12, compact.unicodeScalars.allSatisfy({ shortcutOnly.contains($0) }),
           compact.contains(where: { "⌘⌥⌃⇧".contains($0) }) || compact.lowercased().contains("cmd")
            || compact.lowercased().contains("ctrl") || compact.lowercased().contains("opt") {
            return false
        }
        return true
    }

    private func textOneLine(_ s: String) -> String {
        let p = s.replacingOccurrences(of: "\n", with: " ")
        return p.count > 120 ? String(p.prefix(120)) + "…" : p
    }

    private func readImage(from pb: NSPasteboard) -> NSImage? {
        if let tiff = pb.data(forType: .tiff), let image = NSImage(data: tiff) { return image }
        if let png = pb.data(forType: .png), let image = NSImage(data: png) { return image }
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: nil) as? [URL] {
            for url in urls {
                let ext = url.pathExtension.lowercased()
                if ["png", "jpg", "jpeg", "gif", "webp", "tif", "tiff", "heic"].contains(ext),
                   let image = NSImage(contentsOf: url) {
                    return image
                }
            }
        }
        return nil
    }

    private func hashData(_ data: Data) -> String {
        var h: UInt64 = 5381
        for b in data.prefix(4096) { h = ((h << 5) &+ h) &+ UInt64(b) }
        h = h &+ UInt64(data.count)
        return String(h, radix: 16)
    }

    private func captureText(_ text: String) {
        let hash = hashData(Data(text.utf8))
        commit(ClipboardItem(id: idForHash(hash), kind: .text, text: text, contentHash: hash))
    }

    private func captureColor(hex: String, plain: String) {
        let hash = hashData(Data(hex.utf8))
        commit(ClipboardItem(id: idForHash(hash), kind: .color, text: hex, contentHash: hash))
        _ = plain
    }

    private func captureURL(_ url: String) {
        let hash = hashData(Data(url.utf8))
        commit(ClipboardItem(id: idForHash(hash), kind: .url, text: url, contentHash: hash))
    }

    private func captureFilePaths(_ paths: String) {
        let hash = hashData(Data(paths.utf8))
        commit(ClipboardItem(id: idForHash(hash), kind: .file, text: paths, contentHash: hash))
    }

    private func captureBinary(kind: ClipboardKind, data: Data, ext: String, preview: String, plain: String = "") {
        let hash = hashData(data)
        let id = idForHash(hash)
        let fileName = "\(id).\(ext)"
        try? data.write(to: mediaDir.appendingPathComponent(fileName), options: .atomic)
        commit(ClipboardItem(
            id: id,
            kind: kind,
            text: plain.isEmpty ? preview : plain,
            payloadFileName: fileName,
            contentHash: hash
        ))
    }

    private func captureImage(_ image: NSImage) {
        guard let tiff = image.tiffRepresentation,
              let rep = NSBitmapImageRep(data: tiff),
              let png = rep.representation(using: .png, properties: [:]) else { return }

        let hash = hashData(png)
        let id = idForHash(hash)
        let fileName = "\(id).png"
        do {
            try png.write(to: mediaDir.appendingPathComponent(fileName), options: .atomic)
        } catch { return }

        let w = Int(image.size.width)
        let h = Int(image.size.height)
        let item = ClipboardItem(
            id: id,
            kind: .image,
            text: "Image \(w)×\(h)",
            imageFileName: fileName,
            contentHash: hash
        )
        commit(item)
        TextRecognizer.recognize(imageURL: mediaDir.appendingPathComponent(fileName)) { [weak self] ocr in
            guard let self, let ocr, let idx = self.items.firstIndex(where: { $0.id == id }) else { return }
            self.items[idx].ocrText = ocr
            BlitzDatabase.shared.updateClipboardOCR(id: id, ocr: ocr)
            self.onHistoryChanged?()
        }
    }

    func ingestScreenshot(_ image: NSImage, sourcePath: String) {
        guard SettingsStore.shared.observeScreenshots else { return }
        suppressNextCapture(for: 1.0)
        captureImage(image)
        if let idx = items.indices.first {
            var item = items[idx]
            if item.kind == .image {
                item = ClipboardItem(
                    id: item.id,
                    kind: .image,
                    text: "Screenshot · \(URL(fileURLWithPath: sourcePath).lastPathComponent)",
                    imageFileName: item.imageFileName,
                    createdAt: item.createdAt,
                    ocrText: item.ocrText,
                    contentHash: item.contentHash,
                    pinned: item.pinned
                )
                items[idx] = item
                save()
                onHistoryChanged?()
            }
        }
    }

    private func idForHash(_ hash: String) -> String {
        if SettingsStore.shared.overwriteSameHistory { return hash }
        return UUID().uuidString
    }

    private func commit(_ item: ClipboardItem) {
        let store = SettingsStore.shared
        if let hash = item.contentHash,
           let existing = items.firstIndex(where: { $0.contentHash == hash }) {
            if !store.copySameHistory {
                // Move existing to front if overwrite, else skip
                if store.overwriteSameHistory {
                    let old = items.remove(at: existing)
                    removeMedia(for: old, keeping: item)
                    var merged = item
                    merged.pinned = old.pinned
                    items.insert(merged, at: old.pinned ? 0 : insertIndexForNew())
                    sortPinnedFirst()
                    save()
                    onHistoryChanged?()
                }
                return
            }
        }
        items.insert(item, at: insertIndexForNew())
        trimOverflow()
        save()
        onHistoryChanged?()
    }

    private func insertIndexForNew() -> Int {
        // Keep pinned block at the top.
        items.firstIndex(where: { !$0.pinned }) ?? items.count
    }

    private func sortPinnedFirst() {
        let pinned = items.filter(\.pinned)
        let rest = items.filter { !$0.pinned }
        items = pinned + rest
    }

    @discardableResult
    func togglePin(id: String) -> Bool {
        guard let idx = items.firstIndex(where: { $0.id == id }) else { return false }
        items[idx].pinned.toggle()
        sortPinnedFirst()
        save()
        onHistoryChanged?()
        return items.first(where: { $0.id == id })?.pinned ?? false
    }

    private func removeMedia(for old: ClipboardItem, keeping new: ClipboardItem) {
        if let n = old.imageFileName, n != new.imageFileName {
            try? FileManager.default.removeItem(at: mediaDir.appendingPathComponent(n))
        }
        if let n = old.payloadFileName, n != new.payloadFileName {
            try? FileManager.default.removeItem(at: mediaDir.appendingPathComponent(n))
        }
    }

    private func trimOverflow() {
        while items.count > maxItems {
            guard let idx = items.lastIndex(where: { !$0.pinned }) else { break }
            deleteMedia(items[idx])
            items.remove(at: idx)
        }
    }

    private func deleteMedia(_ item: ClipboardItem) {
        if let name = item.imageFileName {
            try? FileManager.default.removeItem(at: mediaDir.appendingPathComponent(name))
        }
        if let name = item.payloadFileName {
            try? FileManager.default.removeItem(at: mediaDir.appendingPathComponent(name))
        }
    }

    func clear(confirm: Bool = true) {
        if confirm, SettingsStore.shared.showAlertBeforeClearHistory {
            let alert = NSAlert()
            alert.messageText = "Clear Clipboard History"
            alert.informativeText = "Clear unpinned history? Pinned items are kept."
            alert.addButton(withTitle: "Clear")
            alert.addButton(withTitle: "Cancel")
            alert.showsSuppressionButton = true
            NSApp.activate(ignoringOtherApps: true)
            if alert.runModal() != .alertFirstButtonReturn { return }
            if alert.suppressionButton?.state == .on {
                SettingsStore.shared.showAlertBeforeClearHistory = false
            }
        }
        let keep = items.filter(\.pinned)
        for item in items where !item.pinned { deleteMedia(item) }
        items = keep
        save()
        onHistoryChanged?()
    }

    func delete(id: String) {
        guard let idx = items.firstIndex(where: { $0.id == id }) else { return }
        deleteMedia(items[idx])
        items.remove(at: idx)
        save()
        onHistoryChanged?()
    }

    func reorderAfterPaste(id: String) {
        guard SettingsStore.shared.reorderAfterPaste,
              let idx = items.firstIndex(where: { $0.id == id }) else { return }
        let item = items.remove(at: idx)
        if item.pinned {
            items.insert(item, at: 0)
        } else {
            items.insert(item, at: insertIndexForNew())
        }
        sortPinnedFirst()
        save()
        onHistoryChanged?()
    }

    /// Put item on pasteboard and paste into the previously focused app.
    func paste(_ id: String, plainText: Bool = false, deleteAfter: Bool = false) {
        PasteHelper.pasteClipboardItem(id: id, plainText: plainText)
        if deleteAfter {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.6) { [weak self] in
                self?.delete(id: id)
            }
        } else {
            reorderAfterPaste(id: id)
        }
    }

    func writeToPasteboard(_ item: ClipboardItem, plainText: Bool = false) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if plainText {
            pb.declareTypes([.string], owner: nil)
            pb.setString(item.text, forType: .string)
            notePasteboardWritten()
            return
        }
        switch item.kind {
        case .text, .color:
            pb.declareTypes([.string], owner: nil)
            pb.setString(item.text, forType: .string)
        case .url:
            pb.declareTypes([.string, .URL], owner: nil)
            pb.setString(item.text, forType: .string)
            pb.setString(item.text, forType: .URL)
        case .file:
            let urls = item.text.split(separator: "\n").map { URL(fileURLWithPath: String($0)) }
            pb.writeObjects(urls as [NSURL])
        case .image:
            guard let url = imageURL(for: item),
                  let data = try? Data(contentsOf: url),
                  let image = NSImage(data: data) else { return }
            pb.writeObjects([image])
            if let tiff = image.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
            pb.setData(data, forType: .png)
        case .rtf:
            if let url = payloadURL(for: item), let data = try? Data(contentsOf: url) {
                pb.declareTypes([.rtf, .string], owner: nil)
                pb.setData(data, forType: .rtf)
                pb.setString(item.text, forType: .string)
            }
        case .html:
            if let url = payloadURL(for: item), let data = try? Data(contentsOf: url) {
                pb.declareTypes([.html, .string], owner: nil)
                pb.setData(data, forType: .html)
                pb.setString(item.text, forType: .string)
            }
        case .pdf:
            if let url = payloadURL(for: item), let data = try? Data(contentsOf: url) {
                pb.declareTypes([.pdf], owner: nil)
                pb.setData(data, forType: .pdf)
            }
        }
        notePasteboardWritten()
    }

    func matches(_ item: ClipboardItem, query: String) -> Bool {
        let q = query.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        if q.isEmpty { return true }
        if item.kind == .image {
            if "image".contains(q) || "图片".contains(q) || "img".contains(q) || "screenshot".contains(q) {
                return true
            }
            if let ocr = item.ocrText?.lowercased(), ocr.contains(q) { return true }
        }
        if item.kind == .color, item.text.lowercased().contains(q) { return true }
        return item.text.lowercased().contains(q) || item.kind.rawValue.contains(q)
    }

    func searchItems(query: String) -> [SearchItem] {
        items.compactMap { item in
            guard matches(item, query: query) else { return nil }
            let subtitle: String
            switch item.kind {
            case .text: subtitle = "Text · Enter to paste"
            case .image: subtitle = (item.ocrText != nil ? "Image+OCR · " : "Image · ") + "Enter to paste"
            case .rtf: subtitle = "RTF · Enter to paste"
            case .html: subtitle = "HTML · Enter to paste"
            case .pdf: subtitle = "PDF · Enter to paste"
            case .file: subtitle = "File · Enter to paste"
            case .url: subtitle = "URL · Enter to paste"
            case .color: subtitle = "Color · Enter to paste"
            }
            let preview = item.text.replacingOccurrences(of: "\n", with: " ")
            var title: String
            switch item.kind {
            case .image:
                title = item.text
            case .color:
                title = item.text
            default:
                title = preview.isEmpty ? "(\(item.kind.rawValue))" :
                    (preview.count > 120 ? String(preview.prefix(120)) + "…" : preview)
            }
            if item.pinned { title = "★ " + title }
            let sub = item.pinned ? "Pinned · " + subtitle : subtitle
            return SearchItem(
                id: "clip:" + item.id,
                kind: "clipboard",
                title: title,
                subtitle: sub,
                preview: imageURL(for: item)?.path
            )
        }
    }

    private func load() {
        BlitzDatabase.shared.migrateClipboardJSONIfNeeded(jsonURL: storeURL, mediaDir: mediaDir)
        items = filterExistingMedia(BlitzDatabase.shared.loadClipboard())
    }

    private func filterExistingMedia(_ list: [ClipboardItem]) -> [ClipboardItem] {
        list.filter { item in
            if let name = item.imageFileName {
                return FileManager.default.fileExists(atPath: mediaDir.appendingPathComponent(name).path)
            }
            if let name = item.payloadFileName {
                return FileManager.default.fileExists(atPath: mediaDir.appendingPathComponent(name).path)
            }
            return true
        }
    }

    private func save() {
        BlitzDatabase.shared.replaceClipboard(items)
    }
}
