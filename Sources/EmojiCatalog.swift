    /// Returns launcher rows. Empty query → nothing (avoid flooding). Short queries match keywords/name/glyph.
    static func searchItems(matching raw: String, limit: Int = 24) -> [SearchItem] {
        let q = raw.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        guard q.count >= 1 else { return [] }

        // "emoji smile" / ":smile" / "表情 笑"
        var needle = q
        for prefix in ["emoji ", "emoji:", ":", "表情 ", "表情"] {
            if needle.hasPrefix(prefix) {
                needle = String(needle.dropFirst(prefix.count)).trimmingCharacters(in: .whitespaces)
                break
            }
        }
        if needle.isEmpty || needle == "emoji" || needle == "表情" {
            return Array(all.prefix(limit)).map(toItem)
        }

        var scored: [(Int, Entry)] = []
        for e in all {
            let name = e.name.lowercased()
            var score = 0
            if e.glyph == raw || e.glyph == needle { score = 100 }
            else if name == needle { score = 90 }
            else if name.hasPrefix(needle) { score = 80 }
            else if name.contains(needle) { score = 60 }
            else if e.keywords.contains(where: { $0 == needle }) { score = 85 }
            else if e.keywords.contains(where: { $0.hasPrefix(needle) }) { score = 70 }
            else if e.keywords.contains(where: { $0.contains(needle) }) { score = 50 }
            if score > 0 { scored.append((score, e)) }
        }
        scored.sort { lhs, rhs in
            if lhs.0 != rhs.0 { return lhs.0 > rhs.0 }
            return lhs.1.name < rhs.1.name
        }
        return scored.prefix(limit).map { toItem($0.1) }
    }

    private static func toItem(_ e: Entry) -> SearchItem {
        SearchItem(
            id: "emoji:" + e.glyph,
            kind: "emoji",
            title: "\(e.glyph)  \(e.name)",
            subtitle: "Emoji · Enter pastes",
            preview: nil
        )
    }
